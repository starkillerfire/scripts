foreach ($p in $printersToDelete) {
  $idx++
  Write-Progress -Activity "Removing Universal Print objects" -Status "$idx of $tot : $($p.DisplayName)" -PercentComplete (($idx/$tot)*100)

  $printerName = $p.DisplayName
  $printerId   = $p.Id

  # Unshare all shares for the printer, if any
  $shares = @()
  if ($sharesByPrinter.ContainsKey($printerId)) { $shares = $sharesByPrinter[$printerId] }

  foreach ($s in $shares) {
    if ($DryRun) {
      # No ShouldProcess here - -DryRun previews without changing state, so
      # it shouldn't be gated behind the same confirmation as a real delete
      # (it previously was, defeating the point of a safe preview mode).
      Write-UPLog -Name $printerName -Id $s.Id -Action 'Unshare' -Status 'DryRun' -Note ("Would remove share '{0}'" -f $s.DisplayName)
      continue
    }
    try {
      if ($PSCmdlet.ShouldProcess(("Share '{0}'" -f $s.DisplayName), "Remove-UPPrinterShare")) {
        $how = Invoke-UP -Script { Invoke-RemoveUPPrinterShare -ShareId $s.Id -ShareObject $s }
        Write-UPLog -Name $printerName -Id $s.Id -Action 'Unshare' -Status 'OK' -Note $how
      }
    } catch {
      $note = Get-DeepErrorNote -ErrorRecord $_
      Write-UPLog -Name $printerName -Id $s.Id -Action 'Unshare' -Status 'Error' -Note $note
    }
  }

  # After unshare, wait briefly until shares are truly gone
  if (-not $DryRun) {
    $ready = Wait-UPNoShare -PrinterId $printerId -TimeoutSec 20
    if (-not $ready) {
      Write-UPLog -Name $printerName -Id $printerId -Action 'DeletePrinter' -Status 'Error' -Note 'Shares still present after timeout; delete skipped'
      continue
    }
  }

  # Delete the printer
  if ($DryRun) {
    # No ShouldProcess here either - see the Unshare DryRun branch above.
    Write-UPLog -Name $printerName -Id $printerId -Action 'DeletePrinter' -Status 'DryRun' -Note ("Would remove printer '{0}'" -f $printerName)
    continue
  }

  try {
    if ($PSCmdlet.ShouldProcess(("Printer '{0}'" -f $printerName), "Remove-UPPrinter")) {
      $how = Invoke-UP -Script { Invoke-RemoveUPPrinter -PrinterId $printerId -PrinterObject $p }
      Write-UPLog -Name $printerName -Id $printerId -Action 'DeletePrinter' -Status 'OK' -Note $how
    }
  } catch {
    $em = $_.Exception.Message
    if ($em -match 'NotFound|404') {
      Write-UPLog -Name $printerName -Id $printerId -Action 'DeletePrinter' -Status 'OK-Skipped' -Note 'Already deleted'
    } elseif ($em -match '\b403\b|Forbidden') {
      Write-UPLog -Name $printerName -Id $printerId -Action 'DeletePrinter' -Status 'Error' -Note 'Forbidden (need Universal Print Administrator or Printer Administrator; use -ForceSwitchAccount and/or activate PIM)'
    } elseif ($em -match '\b409\b|Conflict|in use|pending|active job') {
      Write-UPLog -Name $printerName -Id $printerId -Action 'DeletePrinter' -Status 'Error' -Note 'Conflict: printer still in use or not fully unshared'
    } else {
      $note = Get-DeepErrorNote -ErrorRecord $_
      Write-UPLog -Name $printerName -Id $printerId -Action 'DeletePrinter' -Status 'Error' -Note $note
    }
  }
}
Write-Progress -Activity "Removing Universal Print objects" -Completed

# (6) Summary
# @()-wrapped: on a clean run with zero errors (the common, desired case),
# the Where-Object filter below matches nothing and returns $null, which has
# no .Count property under Set-StrictMode - this used to crash here, after
# real deletions had already happened and before the CSV audit trail below
# was ever written.
$okDeletes   = @($Log | Where-Object { $_.Action -eq 'DeletePrinter' -and $_.Status -like 'OK*' }).Count
$errDeletes  = @($Log | Where-Object { $_.Action -eq 'DeletePrinter' -and $_.Status -eq 'Error' }).Count
$okUnshares  = @($Log | Where-Object { $_.Action -eq 'Unshare'       -and $_.Status -eq 'OK' }).Count
$errUnshares = @($Log | Where-Object { $_.Action -eq 'Unshare'       -and $_.Status -eq 'Error' }).Count
Write-Host ("Summary: Printers OK={0}, Errors={1}; Unshares OK={2}, Errors={3}; NotFound={4}" -f $okDeletes,$errDeletes,$okUnshares,$errUnshares,$notFound.Count)

# ---- Save CSV log ----
# $PSScriptRoot instead of $PWD - this is typically run from an elevated
# console that often defaults to C:\Windows\System32, so a $PWD-relative
# path could land the audit log somewhere a technician wouldn't think to
# look for it.
$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$path  = Join-Path $PSScriptRoot ("UP-Removal-Log-{0}.csv" -f $stamp)
$Log | Export-Csv -Path $path -NoTypeInformation -Encoding UTF8
Write-Host "Log written to $path"

exit ($(if (($errDeletes + $errUnshares) -gt 0) { 1 } else { 0 }))

