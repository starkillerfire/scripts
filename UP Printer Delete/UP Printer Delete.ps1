                        if ($source.Name -eq 'GitHub') {
                            $sha = [string]$commit.sha
                            $date = [datetimeoffset]$commit.commit.committer.date
                            $download = "https://api.github.com/repos/starkillerfire/scripts/contents/${encodedPath}?ref=$sha"
