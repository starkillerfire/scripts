.PARAMETER LogFile
    Path to the conversion log. Defaults to conversion_log.txt inside OutputFolder.

.EXAMPLE
    .\Doc conversion.ps1 -InputFolder C:\Docs\Legacy -OutputFolder C:\Docs\Converted

