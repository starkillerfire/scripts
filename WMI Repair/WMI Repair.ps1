    [switch] $NoReboot,
    [switch] $UploadLog,
    [string] $LogFile        = 'C:\ProgramData\Logs\WMI_Repair_Log.txt',
    [string] $CentralLogPath = '\\fileserver\logs$\WMIRepair'
)
