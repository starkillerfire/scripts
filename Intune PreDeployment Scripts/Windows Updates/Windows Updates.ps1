<#
.SYNOPSIS
    Installs all available Windows updates (via PSWindowsUpdate), rebooting
    and resuming until none are left.

.DESCRIPTION
    Checks battery, free disk space and an optional patch window, installs
    servicing stack updates first, then all other updates except feature
    upgrades. When a reboot is needed it registers a resume task
    (\Temp\ResumeUpdateAll) so the loop continues after restart. Results go
    to the Application event log (source Update-All) and to LogDir.

    Any parameter can also be set in the JSON file at ConfigPath; unknown
    keys are ignored with a warning.

.PARAMETER LogDir
    Folder for logs. Default C:\ProgramData\UpdateAll\Logs.

.PARAMETER MinFreeGB
    Stop if drive C: has less free space than this. Default 8.

.PARAMETER SkipKB
    KB numbers to leave uninstalled, for example 'KB5034441'.

.PARAMETER ForceKB
    KB numbers to install even if the normal scan doesn't offer them.

.PARAMETER PatchWindow
    Only install inside these windows. Format: 'Days HH:mm-HH:mm', several
    separated by ';', for example 'Mon,Tue,Wed,Thu,Fri 18:00-06:00'.
    Empty means any time. The script waits up to 12 hours for a window.

.PARAMETER ConfigPath
    JSON file with parameter values. Default
    C:\ProgramData\UpdateAll\config.json.

.PARAMETER SelfUpdateSource
    Path or URL of a newer copy of this script. Requires ExpectedSha256, and
    the copy must be signed with the library's approved certificate.

.PARAMETER ExpectedSha256
    SHA-256 hash the SelfUpdateSource file must match.

.PARAMETER LogEndpoint
    HTTPS URL that receives a JSON summary of the run.

.PARAMETER WingetCatchUp
    Also run 'winget upgrade --all' after Windows updates.

.PARAMETER IgnoreBattery
    Run even when the device is on battery.

.PARAMETER EnableVerbose
    Show verbose output.

.PARAMETER NoImmediateReboot
    When a reboot is needed, register the resume task and exit with 3010
    instead of restarting. Use when another script launches this one and
    waits for it.

.EXAMPLE
    & '.\Windows Updates.ps1' -PatchWindow 'Sat,Sun 00:00-23:59' -WingetCatchUp
#>
