    for ($i = 0; $i -lt 3; $i++) {
        try { winget upgrade --all --accept-package-agreements --accept-source-agreements --silent | Out-Null; $wingetOK = $true } catch { $wingetOK = $false }
        if ($wingetOK) { Write-UpdateEvent -m 'winget upgrade OK' -t ([System.Diagnostics.EventLogEntryType]::Information) -id 6001; break } else { Start-Sleep 30 }
    }
}

