            '--id',    $WingetId
            '--silent'
            '--accept-package-agreements'
            '--accept-source-agreements'
            '--scope', 'machine'
            '--architecture', 'x64'
            '--source', 'winget'
            '--disable-interactivity'
            '--log',   $wingetLog
