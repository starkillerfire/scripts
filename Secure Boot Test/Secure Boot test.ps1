function Get-FirmwareType {
    try {
        $peFirmwareType = (Get-ItemProperty -Path 'HKLM:\SYSTEM\CurrentControlSet\Control' -Name PEFirmwareType -ErrorAction Stop).PEFirmwareType
        switch ($peFirmwareType) {
            1 { return 'BIOS' }
