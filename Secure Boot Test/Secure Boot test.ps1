function Get-DellProviderModuleName {
    $mods = Get-Module -ListAvailable -Name 'DellBIOSProvider','Dell.CommandPowerShellProvider' |
            Sort-Object Name
    if ($mods) {
        return ($mods | Select-Object -First 1).Name
