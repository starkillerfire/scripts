        Export-Csv -Path $FailedCSV -NoTypeInformation -Force
    Write-ScriptLog "Failed list saved to $FailedCSV."
} else {
    Write-ScriptLog "All installations completed successfully."
}
Write-ScriptLog "=== Edge remote install complete ==="
exit ($(if ($script:FailedComputers.Count -gt 0) { 1 } else { 0 }))

