$script:FailedComputers = [System.Collections.Generic.List[string]]::new()

function Write-ScriptLog {
    param([string]$Message)
    $line = "$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') - $Message"
    $line | Out-File -Append -FilePath $LogFile -Encoding UTF8
    Write-Host $line
}

function Get-VerifiedInstaller {
    # Downloads the installer once and verifies it's validly signed by
    # Microsoft before it's ever pushed to a single machine. Without this, a
    # compromised CDN response or DNS hijack on $DownloadURL would get
    # copied out to every computer in $InputCSV via PsExec as SYSTEM - this
    # is the only thing standing between that and a fleet-wide compromise.
    $localPath = Join-Path $PSToolsPath $InstallerName
    $isStale = (Test-Path $localPath) -and
               ((Get-Item $localPath).LastWriteTime -lt (Get-Date).AddHours(-$MaxCacheAgeHours))
    if ($isStale) {
        Write-ScriptLog "Cached installer is older than $MaxCacheAgeHours hour(s) - re-downloading rather than pushing a stale build to the whole fleet."
        Remove-Item -Path $localPath -Force -ErrorAction SilentlyContinue
    }
    if (-not (Test-Path $localPath)) {
        Write-ScriptLog "Downloading installer from $DownloadURL ..."
        [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
        Invoke-WebRequest -Uri $DownloadURL -OutFile $localPath -UseBasicParsing -ErrorAction Stop
    }

    $sig = Get-AuthenticodeSignature -FilePath $localPath
    if ($sig.Status -ne 'Valid' -or $sig.SignerCertificate.Subject -notmatch 'O=Microsoft Corporation') {
        Remove-Item -Path $localPath -Force -ErrorAction SilentlyContinue
        throw "Installer at $localPath failed Authenticode validation (status: $($sig.Status)) - refusing to deploy it to any machine."
    }
    Write-ScriptLog "Installer Authenticode signature verified (Microsoft Corporation): $localPath"
    return $localPath
}

function Install-EdgeRemote {
    param([string]$ComputerName, [string]$LocalInstallerPath)

    Write-ScriptLog "[$ComputerName] Starting Edge install..."
    try {
        $localPath = $LocalInstallerPath

        if (-not (Test-Connection -ComputerName $ComputerName -Count 2 -Quiet)) {
            Write-ScriptLog "[$ComputerName] Unreachable - skipping."
            $script:FailedComputers.Add($ComputerName)
            return
        }

        # Stage in ADMIN$\Temp (C:\Windows\Temp) under a random name, not in
        # C:\Temp. Any local user can write to C:\Temp and could swap the MSI
        # before msiexec runs it with admin rights. Standard users cannot
        # modify a file an admin created in C:\Windows\Temp, and the random
        # name stops them planting one in advance.
        $stagedName   = '{0}-{1}' -f [guid]::NewGuid().ToString('N'), $InstallerName
        $uncInstaller = "\\$ComputerName\ADMIN`$\Temp\$stagedName"

        Copy-Item -LiteralPath $localPath -Destination $uncInstaller -ErrorAction Stop

        # Confirm the remote copy is exactly the installer verified above.
        if ((Get-FileHash -LiteralPath $uncInstaller -Algorithm SHA256).Hash -ne (Get-FileHash -LiteralPath $localPath -Algorithm SHA256).Hash) {
            Write-ScriptLog "[$ComputerName] Copied installer does not match the verified file - skipping."
            Remove-Item -LiteralPath $uncInstaller -Force -ErrorAction SilentlyContinue
            $script:FailedComputers.Add($ComputerName)
            return
        }

        # $Arguments is one scalar string (e.g. '/qn /norestart'). Passed as
        # a single token, PowerShell re-quotes it as ONE argument because it
        # contains a space, so msiexec would receive "/qn /norestart" as a
        # single unparseable switch instead of two. Splitting on whitespace
        # passes each flag through as its own argument.
        & "$PSToolsPath\psexec.exe" -accepteula "\\$ComputerName" msiexec.exe /i "C:\Windows\Temp\$stagedName" ($Arguments -split '\s+') 2>&1 | Out-Null
        $rc = $LASTEXITCODE

        if ($rc -in @(0, 3010, 1641)) {
            Write-ScriptLog "[$ComputerName] SUCCESS - Edge installed (exit $rc)."
            if ($rc -ne 0) { Write-ScriptLog "[$ComputerName] NOTE: Reboot pending to complete update." }
        } else {
            Write-ScriptLog "[$ComputerName] ERROR - msiexec exit code: $rc"
            $script:FailedComputers.Add($ComputerName)
        }

        Remove-Item -LiteralPath $uncInstaller -Force -ErrorAction SilentlyContinue
    } catch {
        Write-ScriptLog "[$ComputerName] ERROR: $_"
        $script:FailedComputers.Add($ComputerName)
    }
}

