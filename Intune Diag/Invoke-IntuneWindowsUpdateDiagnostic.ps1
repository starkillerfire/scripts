                    $content = [IO.File]::ReadAllText($temporary)
                    if ([string]::IsNullOrWhiteSpace($content) -or $content -match '(?is)^\s*<(?:!doctype|html)') { throw 'Empty or HTML download rejected.' }
                    if ($extension -in @('.ps1', '.psm1')) {
                        $parseTokens = $null
                        $parseErrors = $null
