# 3) CAPI2 logging (PKI chain & revocation trace)
$capilog = "Microsoft-Windows-CAPI2/Operational"
$capiEnabled = $false
try {
  # wevtutil.exe is a native command - a nonzero exit code doesn't raise a
  # terminating PowerShell error, so try/catch alone never caught a real
  # failure here (e.g. access denied) and it was silently reported as success.
  wevtutil sl "$capilog" /e:true | Out-Null
  if ($LASTEXITCODE -ne 0) { throw "wevtutil exited $LASTEXITCODE" }
  $capiEnabled = $true
  Write-Ok -m "Enabled CAPI2 Operational logging."
} catch { Write-Warn -m "Could not enable CAPI2 logging (try running PowerShell as Administrator). Continuing." }

try {
  Write-Host ""
  Write-Host ">>> Now reproduce the Bluebeam signing failure. When you're done, press ENTER to continue."
  Read-Host | Out-Null

  # Export recent CAPI2 events
  try {
    $Since = (Get-Date).AddMinutes(-[int]$MinutesToCapture).ToString("o")
    $Query = @"
<QueryList>
  <Query Id="0" Path="$capilog">
    <Select>*[System[TimeCreated[@SystemTime >= '$Since']]]</Select>
  </Query>
</QueryList>
"@
    $evtx = Join-Path $EvtDir "CAPI2_Recent.evtx"
    wevtutil epl "$capilog" "$evtx" /q:"$Query" | Out-Null
    Write-Ok -m "Exported recent CAPI2 events → $evtx"
  } catch { Write-Warn -m "CAPI2 export failed (insufficient rights or no events). You can export manually from Event Viewer." }
} finally {
  # This is the only place CAPI2 logging gets turned back off, so it needs
  # to run even if the "reproduce the issue" prompt or the event export
  # above throws unexpectedly - otherwise a single hiccup mid-script would
  # leave verbose CAPI2 logging running indefinitely on the user's machine.
  if ($capiEnabled) {
    try {
      wevtutil sl "$capilog" /e:false | Out-Null
      if ($LASTEXITCODE -ne 0) { throw "wevtutil exited $LASTEXITCODE" }
    } catch { Write-Warn -m "Could not disable CAPI2 logging: $($_.Exception.Message)" }
  }
}

# 4) Cert & revocation diagnostics
function Invoke-CmdOut($file, $cmd, $Arguments) {
  $p = New-Object System.Diagnostics.Process
  $p.StartInfo = New-Object System.Diagnostics.ProcessStartInfo
  $p.StartInfo.FileName = $cmd
  $p.StartInfo.Arguments = $Arguments
  $p.StartInfo.RedirectStandardOutput = $true
  $p.StartInfo.RedirectStandardError  = $true
  $p.StartInfo.UseShellExecute = $false
  $null = $p.Start()
  $out = $p.StandardOutput.ReadToEnd()
  $err = $p.StandardError.ReadToEnd()
  $p.WaitForExit()
  $out | Set-Content $file
  if ($err) { Add-Content $file "`n--- STDERR ---`n$err" }
}

# a) Current user's personal & intermediate stores
# Wrapped like the LocalMachine/gpresult blocks below: with
# $ErrorActionPreference = 'Stop' set globally, an unwrapped certutil
# failure here (missing/blocked certutil.exe, etc.) would abort the whole
# script before the ZIP ever gets produced - a single hiccup shouldn't cost
# the technician the entire support bundle.
try {
  Invoke-CmdOut -file (Join-Path $DiagDir "cert_store_user_my.txt")  -cmd "certutil.exe" -Arguments "-user -store my"
  Invoke-CmdOut -file (Join-Path $DiagDir "cert_store_user_ca.txt")  -cmd "certutil.exe" -Arguments "-user -store ca"
  Invoke-CmdOut -file (Join-Path $DiagDir "cert_store_user_root.txt") -cmd "certutil.exe" -Arguments "-user -store root"
} catch { Write-Warn -m "Could not read current-user certificate stores: $($_.Exception.Message)" }

# b) LocalMachine stores (if admin)
try {
  Invoke-CmdOut -file (Join-Path $DiagDir "cert_store_lm_my.txt")   -cmd "certutil.exe" -Arguments "-store my"
  Invoke-CmdOut -file (Join-Path $DiagDir "cert_store_lm_ca.txt")   -cmd "certutil.exe" -Arguments "-store ca"
  Invoke-CmdOut -file (Join-Path $DiagDir "cert_store_lm_root.txt") -cmd "certutil.exe" -Arguments "-store root"
} catch { Write-Warn -m "Could not read LocalMachine stores (need elevation). Skipping." }

# c) Chain engine config & URL cache
try {
  Invoke-CmdOut -file (Join-Path $DiagDir "cert_chain_config.txt") -cmd "certutil.exe" -Arguments "-getreg chain"
  Invoke-CmdOut -file (Join-Path $DiagDir "cert_urlcache_list.txt") -cmd "certutil.exe" -Arguments "-URLcache *"
} catch { Write-Warn -m "Could not read chain config / URL cache: $($_.Exception.Message)" }

# (Optional) clear user CRL/URL cache AFTER we recorded it - opt-in via -ClearUrlCache
if ($ClearUrlCache) {
  try {
    Invoke-CmdOut -file (Join-Path $DiagDir "cert_urlcache_clear.txt") -cmd "certutil.exe" -Arguments "-URLcache * delete"
  } catch { Write-Warn -m "Could not clear URL cache (non-fatal)." }
} else {
  Write-Info -m "Skipping URL cache clear (pass -ClearUrlCache to force fresh revocation checks)."
}

# 5) GPResult (to show no custom PKI policy)
try {
  $rsop = Join-Path $DiagDir "gpresult.html"
  gpresult /h "$rsop" | Out-Null
  Write-Ok -m "Captured RSOP → $rsop"
} catch { Write-Warn -m "gpresult failed (non-fatal)." }

# 6) Zip it all up
$ZipPath = Join-Path $env:USERPROFILE ("Desktop\\Bluebeam_SupportBundle_$Stamp.zip")
try {
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  [System.IO.Compression.ZipFile]::CreateFromDirectory($OutRoot, $ZipPath)
  Write-Ok -m "Bundle created: $ZipPath"
} catch {
  Write-Warn -m "Could not create the ZIP bundle: $($_.Exception.Message). The collected files are still available, unzipped, at: $OutRoot"
}
