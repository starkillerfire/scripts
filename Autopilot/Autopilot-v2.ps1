                    try {
                        $response = Invoke-RestMethod -Uri $source.Uri -Headers $source.Headers -TimeoutSec 5 -MaximumRedirection 0 -ErrorAction Stop
                    } catch {
                        Write-Verbose "Update check unavailable for $($source.Name): $RepositoryPath"
                        continue
