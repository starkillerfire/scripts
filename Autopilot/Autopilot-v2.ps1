    function Initialize-LockedDirectory {
        [CmdletBinding(SupportsShouldProcess)]
        param([Parameter(Mandatory)][string]$Path)
        if (-not $PSCmdlet.ShouldProcess($Path, 'Create folder writable only by SYSTEM and Administrators')) { return }
        $null = New-Item -Path $Path -ItemType Directory -Force -ErrorAction Stop
        if ((Get-Item -LiteralPath $Path -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) {
            throw "Staging folder $Path is a junction or link; refusing to use it."
        }
        $acl = New-Object System.Security.AccessControl.DirectorySecurity
        $acl.SetAccessRuleProtection($true, $false)
        $admins = New-Object System.Security.Principal.SecurityIdentifier('S-1-5-32-544')
        foreach ($sid in @('S-1-5-18', 'S-1-5-32-544')) {
            $identity = New-Object System.Security.Principal.SecurityIdentifier($sid)
            $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule($identity, 'FullControl', 'ContainerInherit,ObjectInherit', 'None', 'Allow')))
        }
        $acl.SetOwner($admins)
        Set-Acl -LiteralPath $Path -AclObject $acl -ErrorAction Stop
    }

