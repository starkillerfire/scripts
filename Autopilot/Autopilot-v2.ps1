    function Test-SafeParentDirectory {
        [CmdletBinding()]
        [OutputType([bool])]
        param([Parameter(Mandatory)][string]$Path)
        $item = Get-Item -LiteralPath $Path -Force -ErrorAction Stop
        if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { return $false }
